"""Markdown tables from results.json, so the README numbers can be regenerated and checked.

python -m rfdd.report results/ornl
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import pandas as pd

from .faults import BY_KEY
from .plots import METHOD_LABEL


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(_fmt(v) for v in row) + " |")
    return "\n".join(lines)


def _fmt(v: object) -> str:
    if isinstance(v, float):
        return "-" if pd.isna(v) else f"{v:.2f}".rstrip("0").rstrip(".") if abs(v) < 1000 else f"{v:.0f}"
    return str(v)


def headline(results: dict[str, Any]) -> pd.DataFrame:
    s = pd.DataFrame(results["summary"])
    out = pd.DataFrame(
        {
            "Detector": s["method"].map(METHOD_LABEL),
            "Events caught (every fold)": s["events_caught_all_folds"].astype(str) + " / " + s["events"].astype(str),
            "...for the right reason": s["events_caught_right_reason"].astype(str) + " / " + s["events"].astype(str),
            "Detection rate": s["detection_rate"],
            "Median delay, min": s["median_delay_min"],
            "False alarms / normal day": s["false_alarms_per_day"],
            "Normal days with an alarm": s["normal_days_with_alarm"].astype(str) + " / " + s["normal_days"].astype(str),
            "Right diagnosis": s["diagnosis_accuracy"],
        }
    )
    return out


def per_event(results: dict[str, Any], methods: list[str]) -> pd.DataFrame:
    ev = pd.DataFrame(results["event_rows"])
    ev = ev[ev["method"].isin(methods)]
    rows = []
    for (_day, fault), g in ev.groupby(["day", "fault"], sort=False):
        row: dict[str, object] = {"Fault": BY_KEY[fault].name}
        for m in methods:
            e = g[g["method"] == m]
            caught = int(e["detected"].sum())
            delay = e["delay_min"].median()
            diag = e["diagnosis"].dropna()
            cell = f"{caught}/{len(e)}"
            if caught:
                cell += f", {delay:.0f} min"
                if len(diag):
                    cell += f", {diag.mode().iloc[0]}"
            row[METHOD_LABEL[m]] = cell
        rows.append(row)
    return pd.DataFrame(rows)


def tables(results: dict[str, Any]) -> str:
    parts = ["# Result tables (generated by `python -m rfdd.report`)\n"]
    parts += [
        "## Headline (threshold margin {})\n".format(results["config"]["threshold_margin"]),
        _md(headline(results)),
        "",
    ]
    parts += [
        "## Per event: folds detected, median delay, most common diagnosis\n",
        _md(per_event(results, ["rules", "raw", "hybrid", "temp_alarm"])),
        "",
    ]
    parts += [
        "## Other black boxes and ablations\n",
        _md(per_event(results, ["raw_iforest", "raw_knn", "hybrid_no_guard"])),
        "",
    ]
    fa = pd.DataFrame(results["false_alarm_rows"])
    parts += [
        "## False alarms per held-out normal day\n",
        _md(fa.pivot_table(index="method", columns="day", values="episodes", aggfunc="sum").reset_index()),
        "",
    ]
    ph = pd.DataFrame(results["physics_check"])
    parts += [
        "## Physics check\n",
        _md(ph[["fault", "feature", "predicted", "observed_change", "unit", "observed_z", "verdict"]]),
        "",
    ]
    ss = pd.DataFrame(results["sensor_study"])
    if not ss.empty:
        agg = ss.groupby(["sensor", "kind", "size", "expected_check"], sort=False)[
            ["flagged", "process_alarm_with_check", "process_alarm_without_check"]
        ].mean()
        parts += ["## Sensor-fault injections (share of held-out days)\n", _md(agg.reset_index()), ""]
    sm = pd.DataFrame(results["state_masking"])
    parts += [
        "## State masking (rules and hybrid, across thresholds)\n",
        _md(sm[["variant", "method", "margin", "detection_rate", "false_alarms_per_day", "normal_days_with_alarm"]]),
        "",
    ]
    parts += ["## Row-level accuracy trap\n", _md(pd.DataFrame(results["fingerprint_trap"])), ""]
    sw = pd.DataFrame(results["sweep"])
    parts += [
        "## Threshold sweep\n",
        _md(sw[["method", "margin", "detection_rate", "events_caught_all_folds", "false_alarms_per_day"]]),
        "",
    ]
    return "\n".join(parts)


def main() -> None:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "results/ornl")
    results = json.loads((out / "results.json").read_text())
    (out / "tables.md").write_text(tables(results))
    print((out / "tables.md").read_text())


if __name__ == "__main__":
    main()
